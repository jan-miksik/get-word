'use client';

import {
  createContext,
  useContext,
  useEffect,
  useMemo,
  type ReactNode,
} from 'react';
import {
  bundledMessages,
  enMessages,
  getLanguageStatus,
  interpolateMessage,
  REVIEWED_LANGUAGES,
  type I18nKey,
  type I18nMessages,
} from '@/lib/i18n/messages';
import { normalizeLanguageCode } from '@/lib/i18n/languages';

type I18nContextValue = {
  language: string;
  status: 'reviewed' | 'autogenerated' | 'fallback';
  isAutogenerated: boolean;
  isLoading: boolean;
  t: (key: I18nKey, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({
  language,
  children,
}: {
  language?: string | null;
  children: ReactNode;
}) {
  const normalizedLanguage = normalizeLanguageCode(language ?? 'en');
  const bundled = bundledMessages[normalizedLanguage];
  const effectiveLanguage = bundled ? normalizedLanguage : 'en';

  return (
    <I18nValueProvider
      language={effectiveLanguage}
      messages={bundled ?? enMessages}
      status={bundled ? getLanguageStatus(normalizedLanguage) : 'reviewed'}
      isLoading={false}
    >
      {children}
    </I18nValueProvider>
  );
}

function I18nValueProvider({
  language,
  messages,
  status,
  isLoading,
  children,
}: {
  language: string;
  messages: I18nMessages;
  status: I18nContextValue['status'];
  isLoading: boolean;
  children: ReactNode;
}) {

  // Let Chrome/Edge offer their native page translation for the rendered UI.
  // Unsupported saved locales are normalised to English before this point;
  // study text opts out locally with translate="no".
  useEffect(() => {
    document.documentElement.lang = status === 'fallback' ? 'en' : language;
  }, [language, status]);

  const value = useMemo<I18nContextValue>(() => {
    return {
      language,
      status,
      isAutogenerated: !REVIEWED_LANGUAGES.has(language),
      isLoading,
      t: (key, values) => interpolateMessage(messages[key] ?? enMessages[key] ?? key, values),
    };
  }, [isLoading, language, messages, status]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    return {
      language: 'en',
      status: 'reviewed',
      isAutogenerated: false,
      isLoading: false,
      t: (key, values) => interpolateMessage(enMessages[key] ?? key, values),
    };
  }
  return ctx;
}
