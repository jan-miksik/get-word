import { NextRequest, NextResponse } from "next/server";
import {
  applyAutogeneratedCommonWordListRepairs,
  previewAutogeneratedCommonWordListRepair,
  repairAutogeneratedCommonWordList,
  type AutogeneratedCommonListRepairPreview,
} from "@/features/learning/onboarding/server/autogenerate-common-list";
import { getListById } from "@/lib/db";
import {
  forbiddenResponse,
  isEditor,
  resolveUserFromRequest,
  unauthorizedResponse,
} from "@/lib/auth";
import { serializeWordList } from "@/lib/word-list-dto";
import { OpenRouterChatError } from "@/lib/openrouter-chat";
import { normalizeAcceptedAnswersForDisplay } from "@/lib/word-item-accepted-answers";

type RouteContext = { params: Promise<{ id: string }> };

function serializeRepairPreview(preview: AutogeneratedCommonListRepairPreview) {
  return {
    item_count: preview.itemCount,
    category_count: preview.categoryCount,
    provider: preview.provider,
    seed_kind: preview.seedKind,
    seed_list_id: preview.seedListId,
    description: preview.description,
    categories: preview.categories,
    items: preview.items.map((item) => ({
      text_known: item.textKnown,
      text_target: item.textTarget,
      category_name: item.categoryName,
      known_audio_asset_id: item.knownAudioAssetId ?? null,
      known_audio_status: item.knownAudioStatus ?? "none",
      audio_asset_id: item.audioAssetId ?? null,
      audio_status: item.audioStatus ?? "none",
      canonical_word_id: item.canonicalWordId ?? null,
      notes: item.notes ?? null,
      accepted_known: item.acceptedKnown ?? [],
      accepted_target: item.acceptedTarget ?? [],
    })),
    repairs: preview.repairs.map((repair) => ({
      current_item_id: repair.currentItemId,
      text_known: repair.textKnown,
      proposed_text_known: repair.proposedTextKnown,
      current_text_target: repair.currentTextTarget,
      proposed_text_target: repair.proposedTextTarget,
      accepted_known: repair.acceptedKnown ?? [],
      accepted_target: repair.acceptedTarget ?? [],
      current_category_name: repair.currentCategoryName,
      proposed_category_name: repair.proposedCategoryName,
      reason: repair.reason,
      known_audio_asset_id: repair.knownAudioAssetId ?? null,
      known_audio_status: repair.knownAudioStatus ?? "none",
      audio_asset_id: repair.audioAssetId ?? null,
      audio_status: repair.audioStatus ?? "none",
      canonical_word_id: repair.canonicalWordId ?? null,
      notes: repair.notes ?? null,
      selected_by_default: repair.selectedByDefault,
    })),
    unchanged: preview.unchanged.map((item) => ({
      item_id: item.itemId,
      text_known: item.textKnown,
      text_target: item.textTarget,
      category_name: item.categoryName,
    })),
    ignored_suggestion_count: preview.ignoredSuggestionCount,
    stats: {
      translations: preview.translationStats,
    },
  };
}

function parseRepairPreview(value: unknown): AutogeneratedCommonListRepairPreview | null {
  if (!value || typeof value !== "object") return null;
  const raw = value as Record<string, unknown>;
  const items = Array.isArray(raw.items) ? raw.items : null;
  const categories = Array.isArray(raw.categories) ? raw.categories : null;
  const repairs = Array.isArray(raw.repairs) ? raw.repairs : [];
  const unchanged = Array.isArray(raw.unchanged) ? raw.unchanged : [];
  const stats = raw.stats && typeof raw.stats === "object"
    ? (raw.stats as Record<string, unknown>).translations
    : raw.translationStats;
  const translations = stats && typeof stats === "object" ? stats as Record<string, unknown> : null;
  if (!items || !categories || !translations) return null;
  if (typeof raw.description !== "string") return null;
  if (typeof raw.provider !== "string" || typeof raw.seed_kind !== "string") return null;

  const parsedItems = items.map((item) => {
    if (!item || typeof item !== "object") return null;
    const row = item as Record<string, unknown>;
    if (typeof row.text_known !== "string" || typeof row.text_target !== "string") return null;
    if (typeof row.category_name !== "string") return null;
    return {
      textKnown: row.text_known,
      textTarget: row.text_target,
      categoryName: row.category_name,
      knownAudioAssetId: typeof row.known_audio_asset_id === "string" ? row.known_audio_asset_id : null,
      knownAudioStatus: row.known_audio_status === "ready" ? "ready" as const : "none" as const,
      audioAssetId: typeof row.audio_asset_id === "string" ? row.audio_asset_id : null,
      audioStatus: row.audio_status === "ready" ? "ready" as const : "none" as const,
      canonicalWordId: typeof row.canonical_word_id === "string" ? row.canonical_word_id : null,
      notes: typeof row.notes === "string" ? row.notes : null,
      // The preview echoes back through the client, so re-validate the
      // accepted answers; previews from before the fields existed parse fine.
      acceptedKnown: normalizeAcceptedAnswersForDisplay(row.accepted_known, row.text_known),
      acceptedTarget: normalizeAcceptedAnswersForDisplay(row.accepted_target, row.text_target),
    };
  });
  if (parsedItems.some((item) => item === null)) return null;
  const parsedRepairs = repairs.map((repair) => {
    if (!repair || typeof repair !== "object") return null;
    const row = repair as Record<string, unknown>;
    if (typeof row.current_item_id !== "string") return null;
    if (typeof row.text_known !== "string" || typeof row.proposed_text_target !== "string") return null;
    return {
      currentItemId: row.current_item_id,
      textKnown: row.text_known,
      proposedTextKnown: typeof row.proposed_text_known === "string" ? row.proposed_text_known : row.text_known,
      currentTextTarget: typeof row.current_text_target === "string" ? row.current_text_target : null,
      proposedTextTarget: row.proposed_text_target,
      acceptedKnown: normalizeAcceptedAnswersForDisplay(
        row.accepted_known,
        typeof row.proposed_text_known === "string" ? row.proposed_text_known : row.text_known,
      ),
      acceptedTarget: normalizeAcceptedAnswersForDisplay(
        row.accepted_target,
        row.proposed_text_target,
      ),
      currentCategoryName: typeof row.current_category_name === "string" ? row.current_category_name : "",
      proposedCategoryName: typeof row.proposed_category_name === "string" ? row.proposed_category_name : "",
      reason: row.reason === "known_side" ? "known_side" as const : "translation" as const,
      knownAudioAssetId: typeof row.known_audio_asset_id === "string" ? row.known_audio_asset_id : null,
      knownAudioStatus: row.known_audio_status === "ready" ? "ready" as const : "none" as const,
      audioAssetId: typeof row.audio_asset_id === "string" ? row.audio_asset_id : null,
      audioStatus: row.audio_status === "ready" ? "ready" as const : "none" as const,
      canonicalWordId: typeof row.canonical_word_id === "string" ? row.canonical_word_id : null,
      notes: typeof row.notes === "string" ? row.notes : null,
      selectedByDefault: row.selected_by_default !== false,
    };
  });
  if (parsedRepairs.some((repair) => repair === null)) return null;
  const parsedUnchanged = unchanged
    .filter((item): item is Record<string, unknown> => Boolean(item) && typeof item === "object")
    .map((item) => ({
      itemId: typeof item.item_id === "string" ? item.item_id : "",
      textKnown: typeof item.text_known === "string" ? item.text_known : "",
      textTarget: typeof item.text_target === "string" ? item.text_target : null,
      categoryName: typeof item.category_name === "string" ? item.category_name : "",
    }))
    .filter((item) => item.itemId);

  return {
    itemCount: parsedItems.length,
    categoryCount: categories.length,
    provider: raw.provider as AutogeneratedCommonListRepairPreview["provider"],
    seedKind: raw.seed_kind as AutogeneratedCommonListRepairPreview["seedKind"],
    seedListId: typeof raw.seed_list_id === "string" ? raw.seed_list_id : null,
    description: raw.description,
    categories: categories.filter((category): category is string => typeof category === "string"),
    items: parsedItems as AutogeneratedCommonListRepairPreview["items"],
    repairs: parsedRepairs as AutogeneratedCommonListRepairPreview["repairs"],
    unchanged: parsedUnchanged,
    ignoredSuggestionCount: Number(raw.ignored_suggestion_count ?? 0),
    translationStats: {
      reused: Number(translations.reused ?? 0),
      generated: Number(translations.generated ?? 0),
    },
  };
}

export async function POST(request: NextRequest, context: RouteContext) {
  const user = await resolveUserFromRequest(request);
  if (!user) return unauthorizedResponse();
  if (!isEditor(user)) return forbiddenResponse("Editor role required");

  const { id: listId } = await context.params;
  const list = await getListById(listId);
  if (!list) {
    return NextResponse.json({ error: "List not found" }, { status: 404 });
  }
  if (!list.isAutogenerated) {
    return NextResponse.json(
      { error: "Only autogenerated lists can be repaired this way" },
      { status: 400 },
    );
  }

  try {
    const body = await request.json().catch(() => ({}));
    if (body?.mode === "preview") {
      const preview = await previewAutogeneratedCommonWordListRepair({
        listId,
        userId: user.id,
        userRole: "editor",
      });
      return NextResponse.json({ preview: serializeRepairPreview(preview) });
    }

    const preview = body?.mode === "apply_preview"
      ? parseRepairPreview(body.preview)
      : null;
    if (body?.mode === "apply_preview" && !preview) {
      return NextResponse.json({ error: "Invalid repair preview" }, { status: 400 });
    }

    const selectedRepairItemIds = Array.isArray(body?.selected_repair_item_ids)
      ? body.selected_repair_item_ids.filter((id: unknown): id is string => typeof id === "string")
      : [];
    const result = preview
      ? await applyAutogeneratedCommonWordListRepairs({
          listId,
          userId: user.id,
          preview,
          selectedRepairItemIds,
        })
      : await repairAutogeneratedCommonWordList({
          listId,
          userId: user.id,
          userRole: "editor",
        });
    return NextResponse.json({
      list: serializeWordList(result.list),
      item_count: result.itemCount,
      provider: result.provider,
      seed_kind: result.seedKind,
      seed_list_id: result.seedListId,
      stats: {
        translations: result.translationStats,
      },
    });
  } catch (err) {
    if (err instanceof OpenRouterChatError && err.isOutOfCredits) {
      return NextResponse.json(
        {
          error:
            "Automatic repair is temporarily unavailable because the OpenRouter server account is out of credits.",
          code: "OPENROUTER_OUT_OF_CREDITS",
        },
        { status: 503 },
      );
    }
    console.error("[Get Word lists] repair autogenerated list failed", err);
    return NextResponse.json(
      { error: err instanceof Error ? err.message : "List repair failed" },
      { status: 500 },
    );
  }
}
