import { beforeEach, describe, expect, it, vi } from "vitest";
import { NextRequest } from "next/server";

const mockResolveUserFromRequest = vi.fn();
const mockIsEditor = vi.fn();
const mockGetListById = vi.fn();
const mockPreviewAutogeneratedCommonWordListRepair = vi.fn();
const mockRepairAutogeneratedCommonWordList = vi.fn();
const mockApplyAutogeneratedCommonWordListRepairs = vi.fn();

vi.mock("@/lib/auth", () => ({
  resolveUserFromRequest: (...args: unknown[]) => mockResolveUserFromRequest(...args),
  unauthorizedResponse: () =>
    new Response(JSON.stringify({ error: "Authentication required" }), {
      status: 401,
      headers: { "content-type": "application/json" },
    }),
  forbiddenResponse: (message: string) =>
    new Response(JSON.stringify({ error: message }), {
      status: 403,
      headers: { "content-type": "application/json" },
    }),
  isEditor: (...args: unknown[]) => mockIsEditor(...args),
}));

vi.mock("@/lib/db", () => ({
  getListById: (...args: unknown[]) => mockGetListById(...args),
}));

vi.mock("@/features/learning/onboarding/server/autogenerate-common-list", () => ({
  applyAutogeneratedCommonWordListRepairs: (...args: unknown[]) =>
    mockApplyAutogeneratedCommonWordListRepairs(...args),
  previewAutogeneratedCommonWordListRepair: (...args: unknown[]) =>
    mockPreviewAutogeneratedCommonWordListRepair(...args),
  repairAutogeneratedCommonWordList: (...args: unknown[]) =>
    mockRepairAutogeneratedCommonWordList(...args),
}));

import { POST } from "../[id]/repair-autogenerated/route";

describe("POST /api/lists/[id]/repair-autogenerated", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockResolveUserFromRequest.mockResolvedValue({ id: "editor-1", userRole: "editor" });
    mockIsEditor.mockReturnValue(true);
    mockGetListById.mockResolvedValue({
      id: "list-1",
      ownerId: "owner-1",
      name: "Thai - Chinese",
      description: null,
      languageFrom: "th",
      languageTo: "zh",
      isPublic: true,
      isCommon: false,
      isRecommended: true,
      isAutogenerated: true,
      shareToken: null,
      createdAt: new Date("2026-01-01T00:00:00.000Z"),
      updatedAt: new Date("2026-01-01T00:00:00.000Z"),
    });
    mockPreviewAutogeneratedCommonWordListRepair.mockResolvedValue({
      itemCount: 2,
      categoryCount: 1,
      provider: "seed_copy",
      seedKind: "exact_pair",
      seedListId: "seed-1",
      description: "Preview from seed",
      categories: ["Basics"],
      items: [
        {
          textKnown: "hello",
          textTarget: "你好",
          categoryName: "Basics",
          knownAudioAssetId: null,
          knownAudioStatus: "none",
          audioAssetId: null,
          audioStatus: "none",
          canonicalWordId: "item-1",
          notes: null,
        },
        {
          textKnown: "thanks",
          textTarget: "谢谢",
          categoryName: "Basics",
          knownAudioAssetId: "asset-1",
          knownAudioStatus: "ready",
          audioAssetId: "asset-2",
          audioStatus: "ready",
          canonicalWordId: "item-2",
          notes: "note",
        },
      ],
      repairs: [],
      unchanged: [],
      ignoredSuggestionCount: 0,
      translationStats: { reused: 2, generated: 0 },
    });
    mockRepairAutogeneratedCommonWordList.mockResolvedValue({
      list: {
        id: "list-1",
        ownerId: "owner-1",
        name: "Thai - Chinese",
        description: "Repaired from seed",
        languageFrom: "th",
        languageTo: "zh",
        isPublic: true,
        isCommon: false,
        isRecommended: true,
        isAutogenerated: true,
        shareToken: null,
        createdAt: new Date("2026-01-01T00:00:00.000Z"),
        updatedAt: new Date("2026-01-02T00:00:00.000Z"),
      },
      itemCount: 120,
      provider: "openrouter",
      seedKind: "translation_base",
      seedListId: "seed-1",
      reusedExisting: false,
      translationStats: { reused: 0, generated: 120 },
    });
    mockApplyAutogeneratedCommonWordListRepairs.mockResolvedValue({
      list: {
        id: "list-1",
        ownerId: "owner-1",
        name: "Thai - Chinese",
        description: "Repaired from seed",
        languageFrom: "th",
        languageTo: "zh",
        isPublic: true,
        isCommon: false,
        isRecommended: true,
        isAutogenerated: true,
        shareToken: null,
        createdAt: new Date("2026-01-01T00:00:00.000Z"),
        updatedAt: new Date("2026-01-02T00:00:00.000Z"),
      },
      itemCount: 1,
      provider: "seed_copy",
      seedKind: "exact_pair",
      seedListId: "seed-1",
      reusedExisting: false,
      translationStats: { reused: 1, generated: 0 },
    });
  });

  it("requires an editor user", async () => {
    mockIsEditor.mockReturnValue(false);
    const req = new NextRequest("http://localhost/api/lists/list-1/repair-autogenerated", {
      method: "POST",
    });

    const res = await POST(req, { params: Promise.resolve({ id: "list-1" }) });

    expect(res.status).toBe(403);
    expect(mockRepairAutogeneratedCommonWordList).not.toHaveBeenCalled();
  });

  it("only repairs autogenerated lists", async () => {
    mockGetListById.mockResolvedValueOnce({
      id: "list-1",
      isAutogenerated: false,
    });
    const req = new NextRequest("http://localhost/api/lists/list-1/repair-autogenerated", {
      method: "POST",
    });

    const res = await POST(req, { params: Promise.resolve({ id: "list-1" }) });
    const body = await res.json();

    expect(res.status).toBe(400);
    expect(body.error).toMatch(/autogenerated/i);
    expect(mockRepairAutogeneratedCommonWordList).not.toHaveBeenCalled();
  });

  it("repairs the existing list id and returns the updated list", async () => {
    const req = new NextRequest("http://localhost/api/lists/list-1/repair-autogenerated", {
      method: "POST",
    });

    const res = await POST(req, { params: Promise.resolve({ id: "list-1" }) });
    const body = await res.json();

    expect(res.status).toBe(200);
    expect(mockRepairAutogeneratedCommonWordList).toHaveBeenCalledWith({
      listId: "list-1",
      userId: "editor-1",
      userRole: "editor",
    });
    expect(body.list.id).toBe("list-1");
    expect(body.item_count).toBe(120);
    expect(body.seed_list_id).toBe("seed-1");
  });

  it("previews the replacement content without repairing the list", async () => {
    const req = new NextRequest("http://localhost/api/lists/list-1/repair-autogenerated", {
      method: "POST",
      body: JSON.stringify({ mode: "preview" }),
    });

    const res = await POST(req, { params: Promise.resolve({ id: "list-1" }) });
    const body = await res.json();

    expect(res.status).toBe(200);
    expect(mockPreviewAutogeneratedCommonWordListRepair).toHaveBeenCalledWith({
      listId: "list-1",
      userId: "editor-1",
      userRole: "editor",
    });
    expect(mockRepairAutogeneratedCommonWordList).not.toHaveBeenCalled();
    expect(body.preview.item_count).toBe(2);
    expect(body.preview.categories).toEqual(["Basics"]);
    expect(body.preview.items[1].text_target).toBe("谢谢");
  });

  it("applies the preview payload instead of generating a fresh repair", async () => {
    const preview = {
      provider: "seed_copy",
      seed_kind: "exact_pair",
      seed_list_id: "seed-1",
      description: "Preview from seed",
      categories: ["Basics"],
      items: [
        {
          text_known: "hello",
          text_target: "你好",
          category_name: "Basics",
          known_audio_asset_id: null,
          known_audio_status: "none",
          audio_asset_id: null,
          audio_status: "none",
          canonical_word_id: "item-1",
          notes: null,
        },
      ],
      repairs: [
        {
          current_item_id: "current-1",
          text_known: "hello",
          proposed_text_known: "สวัสดี",
          current_text_target: "哈啰",
          proposed_text_target: "你好",
          current_category_name: "Basics",
          proposed_category_name: "Basics",
          reason: "known_side",
          audio_asset_id: null,
          audio_status: "none",
          canonical_word_id: "item-1",
          notes: null,
          selected_by_default: true,
        },
      ],
      unchanged: [
        {
          item_id: "current-2",
          text_known: "thanks",
          text_target: "谢谢",
          category_name: "Basics",
        },
      ],
      ignored_suggestion_count: 0,
      stats: { translations: { reused: 1, generated: 0 } },
    };
    const req = new NextRequest("http://localhost/api/lists/list-1/repair-autogenerated", {
      method: "POST",
      body: JSON.stringify({
        mode: "apply_preview",
        preview,
        selected_repair_item_ids: ["current-1"],
      }),
    });

    const res = await POST(req, { params: Promise.resolve({ id: "list-1" }) });

    expect(res.status).toBe(200);
    expect(mockPreviewAutogeneratedCommonWordListRepair).not.toHaveBeenCalled();
    expect(mockRepairAutogeneratedCommonWordList).not.toHaveBeenCalled();
    expect(mockApplyAutogeneratedCommonWordListRepairs).toHaveBeenCalledWith({
      listId: "list-1",
      userId: "editor-1",
      selectedRepairItemIds: ["current-1"],
      preview: expect.objectContaining({
        description: "Preview from seed",
        repairs: [
          expect.objectContaining({
            currentItemId: "current-1",
            proposedTextKnown: "สวัสดี",
            currentTextTarget: "哈啰",
            proposedTextTarget: "你好",
            reason: "known_side",
          }),
        ],
        items: [
          expect.objectContaining({
            textKnown: "hello",
            textTarget: "你好",
            categoryName: "Basics",
          }),
        ],
      }),
    });
  });
});
