'use client';

import { useState } from 'react';
import { createPortal } from 'react-dom';
import { useI18n } from '@/components/I18nProvider';
import type { WordList } from '@/features/lists/types';
import type { RepairAutogeneratedListPreview } from '@/features/lists/client/actions';
import { copyTextToClipboard } from '@/lib/clipboard';

export function RepairPreviewModal({
  list,
  preview,
  currentWordCount,
  currentCategoryCount,
  repairing,
  onConfirm,
  onCancel,
}: {
  list: WordList;
  preview: RepairAutogeneratedListPreview;
  currentWordCount: number;
  currentCategoryCount: number;
  repairing: boolean;
  onConfirm: (selectedRepairItemIds: string[]) => void;
  onCancel: () => void;
}) {
  const { t } = useI18n();
  const [copyStatus, setCopyStatus] = useState<'idle' | 'copied' | 'failed'>('idle');
  const [selectedIds, setSelectedIds] = useState<Set<string>>(
    () => new Set(preview.repairs.filter((repair) => repair.selectedByDefault).map((repair) => repair.currentItemId)),
  );
  const selectedCount = selectedIds.size;
  const unchangedPreview = preview.unchanged.slice(0, 20);
  const hasMoreUnchanged = preview.unchanged.length > unchangedPreview.length;

  function toggleRepair(itemId: string) {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      if (next.has(itemId)) next.delete(itemId);
      else next.add(itemId);
      return next;
    });
  }

  function buildCopyText() {
    const selected = preview.repairs.filter((repair) => selectedIds.has(repair.currentItemId));
    const skipped = preview.repairs.filter((repair) => !selectedIds.has(repair.currentItemId));
    const lines = [
      `Repair preview for: ${list.name}`,
      `Language pair: ${list.languageFrom} -> ${list.languageTo}`,
      `Source: ${preview.seedKind || preview.provider}${preview.seedListId ? ` (${preview.seedListId})` : ''}`,
      `Current list: ${currentWordCount} words, ${currentCategoryCount} categories`,
      `Suggested repairs: ${preview.repairs.length}; selected: ${selected.length}; skipped: ${skipped.length}`,
      `Unchanged: ${preview.unchanged.length}; ignored generated suggestions: ${preview.ignoredSuggestionCount}`,
      '',
      'Please review whether the selected repairs are correct. Focus on whether the Thai source text and Chinese target text match each other, and flag any repairs that should not be applied.',
      '',
      'SELECTED REPAIRS',
      ...selected.flatMap((repair, index) => [
        `${index + 1}. ${repair.reason === 'known_side' ? 'source text' : 'translation'} | ${repair.currentItemId}`,
        `   current known: ${repair.textKnown}`,
        `   proposed known: ${repair.proposedTextKnown}`,
        `   current target: ${repair.currentTextTarget ?? ''}`,
        `   proposed target: ${repair.proposedTextTarget}`,
        `   category: ${repair.currentCategoryName}`,
      ]),
      '',
      'SKIPPED SUGGESTED REPAIRS',
      ...skipped.flatMap((repair, index) => [
        `${index + 1}. ${repair.reason === 'known_side' ? 'source text' : 'translation'} | ${repair.currentItemId}`,
        `   current known: ${repair.textKnown}`,
        `   proposed known: ${repair.proposedTextKnown}`,
        `   current target: ${repair.currentTextTarget ?? ''}`,
        `   proposed target: ${repair.proposedTextTarget}`,
        `   category: ${repair.currentCategoryName}`,
      ]),
      '',
      'UNCHANGED ITEMS',
      ...preview.unchanged.map((item, index) =>
        `${index + 1}. ${item.textKnown}\t${item.textTarget ?? ''}\t${item.categoryName}`,
      ),
    ];
    return lines.join('\n');
  }

  async function handleCopyPreview() {
    try {
      await copyTextToClipboard(buildCopyText());
      setCopyStatus('copied');
    } catch {
      setCopyStatus('failed');
    }
  }

  const modal = (
    <div
      className="fixed inset-0 z-[80] flex items-center justify-center bg-black/60 p-4"
      onClick={onCancel}
    >
      <div
        className="flex max-h-[88vh] w-full max-w-5xl flex-col rounded-2xl border border-border-subtle bg-background shadow-xl"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="border-b border-border-subtle p-5">
          <h2 className="text-base font-semibold text-text">
            {t('lists.repairPreviewTitle', { name: list.name })}
          </h2>
          <p className="mt-2 text-sm text-text-soft">{t('lists.repairPreviewMessage')}</p>
        </div>

        <div className="flex-1 overflow-y-auto p-5">
          <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
            <div className="rounded-lg border border-border-subtle bg-background-elevated p-3">
              <div className="text-xs font-medium uppercase text-text-soft">{t('lists.repairPreviewBefore')}</div>
              <div className="mt-1 text-sm text-text">
                {t('lists.repairPreviewCounts', { words: currentWordCount, categories: currentCategoryCount })}
              </div>
            </div>
            <div className="rounded-lg border border-fresh/25 bg-fresh/10 p-3">
              <div className="text-xs font-medium uppercase text-text-soft">{t('lists.repairPreviewSuggested')}</div>
              <div className="mt-1 text-sm text-text">
                {t('lists.repairPreviewRepairCount', { count: preview.repairs.length })}
              </div>
            </div>
            <div className="rounded-lg border border-border-subtle bg-background-elevated p-3">
              <div className="text-xs font-medium uppercase text-text-soft">{t('lists.repairPreviewSource')}</div>
              <div className="mt-1 text-sm text-text">{preview.seedKind || preview.provider}</div>
            </div>
            <div className="rounded-lg border border-border-subtle bg-background-elevated p-3">
              <div className="text-xs font-medium uppercase text-text-soft">{t('lists.repairPreviewTranslations')}</div>
              <div className="mt-1 text-sm text-text">
                {t('lists.repairPreviewTranslationCounts', {
                  reused: preview.translationStats.reused,
                  generated: preview.translationStats.generated,
                })}
              </div>
            </div>
          </div>

          {preview.description ? (
            <p className="mt-4 rounded-lg border border-border-subtle bg-background-elevated p-3 text-sm text-text-soft">
              {preview.description}
            </p>
          ) : null}
          {preview.ignoredSuggestionCount > 0 ? (
            <p className="mt-3 rounded-lg border border-border-subtle bg-background-elevated p-3 text-sm text-text-soft">
              {t('lists.repairPreviewIgnoredSuggestions', { count: preview.ignoredSuggestionCount })}
            </p>
          ) : null}

          <div className="mt-5 space-y-4">
            <section className="rounded-lg border border-border-subtle">
              <div className="flex flex-wrap items-center justify-between gap-2 border-b border-border-subtle bg-background-elevated px-3 py-2">
                <h3 className="text-sm font-semibold text-text">{t('lists.repairPreviewSuggestedTitle')}</h3>
                <div className="flex items-center gap-2 text-xs text-text-soft">
                  <span>{t('lists.repairPreviewSelectedCount', { selected: selectedCount, total: preview.repairs.length })}</span>
                  <button
                    type="button"
                    className="rounded border border-border-subtle px-2 py-1 hover:bg-background"
                    onClick={handleCopyPreview}
                    disabled={repairing}
                  >
                    {copyStatus === 'copied'
                      ? t('lists.repairPreviewCopied')
                      : copyStatus === 'failed'
                        ? t('lists.repairPreviewCopyFailed')
                        : t('lists.repairPreviewCopy')}
                  </button>
                  <button
                    type="button"
                    className="rounded border border-border-subtle px-2 py-1 hover:bg-background"
                    onClick={() => setSelectedIds(new Set(preview.repairs.map((repair) => repair.currentItemId)))}
                    disabled={repairing}
                  >
                    {t('lists.repairPreviewSelectAll')}
                  </button>
                  <button
                    type="button"
                    className="rounded border border-border-subtle px-2 py-1 hover:bg-background"
                    onClick={() => setSelectedIds(new Set())}
                    disabled={repairing}
                  >
                    {t('lists.repairPreviewSelectNone')}
                  </button>
                </div>
              </div>

              {preview.repairs.length > 0 ? (
                <div className="divide-y divide-border-subtle">
                  {preview.repairs.map((repair) => (
                    <label
                      key={repair.currentItemId}
                      className="grid cursor-pointer gap-2 px-3 py-3 text-sm sm:grid-cols-[auto_1fr]"
                    >
                      <input
                        type="checkbox"
                        className="mt-1 size-4 accent-accent"
                        checked={selectedIds.has(repair.currentItemId)}
                        onChange={() => toggleRepair(repair.currentItemId)}
                        disabled={repairing}
                      />
                      <span className="grid gap-2">
                        <span className="flex flex-wrap items-center gap-2">
                          <span className="font-medium text-text">{repair.textKnown}</span>
                          <span className="rounded-full border border-border-subtle px-2 py-0.5 text-xs text-text-soft">
                            {repair.reason === 'known_side'
                              ? t('lists.repairPreviewKnownSideReason')
                              : t('lists.repairPreviewTranslationReason')}
                          </span>
                        </span>

                        {repair.textKnown !== repair.proposedTextKnown ? (
                          <span className="grid gap-1 sm:grid-cols-2">
                            <span className="rounded border border-danger/20 bg-danger/5 px-2 py-1 text-text-soft">
                              {repair.textKnown}
                            </span>
                            <span className="rounded border border-fresh/25 bg-fresh/10 px-2 py-1 text-text">
                              {repair.proposedTextKnown}
                            </span>
                          </span>
                        ) : null}

                        {repair.currentTextTarget !== repair.proposedTextTarget ? (
                          <span className="grid gap-1 sm:grid-cols-2">
                            <span className="rounded border border-danger/20 bg-danger/5 px-2 py-1 text-text-soft">
                              {repair.currentTextTarget || t('lists.noTranslationYet')}
                            </span>
                            <span className="rounded border border-fresh/25 bg-fresh/10 px-2 py-1 text-text">
                              {repair.proposedTextTarget}
                            </span>
                          </span>
                        ) : (
                          <span className="rounded border border-border-subtle bg-background-elevated px-2 py-1 text-text-soft">
                            {repair.proposedTextTarget}
                          </span>
                        )}

                        <span className="text-xs text-text-soft">
                          {repair.currentCategoryName}
                          {repair.knownAudioAssetId || repair.audioAssetId ? ` · ${t('lists.repairPreviewAudioKept')}` : ''}
                        </span>
                      </span>
                    </label>
                  ))}
                </div>
              ) : (
                <p className="px-3 py-4 text-sm text-text-soft">{t('lists.repairPreviewNoSuggestions')}</p>
              )}
            </section>

            <section className="rounded-lg border border-border-subtle">
                <div className="flex items-center justify-between border-b border-border-subtle bg-background-elevated px-3 py-2">
                  <h3 className="text-sm font-semibold text-text">{t('lists.repairPreviewUnchangedTitle')}</h3>
                  <span className="text-xs text-text-soft">{t('lists.wordsCount', { count: preview.unchanged.length })}</span>
                </div>
                <div className="divide-y divide-border-subtle">
                  {unchangedPreview.map((item) => (
                    <div
                      key={item.itemId}
                      className="grid gap-1 px-3 py-2 text-sm sm:grid-cols-[1fr_1fr_auto]"
                    >
                      <span className="min-w-0 break-words text-text">{item.textKnown}</span>
                      <span className="min-w-0 break-words text-text-soft">{item.textTarget}</span>
                      <span className="text-xs text-text-soft">{item.categoryName}</span>
                    </div>
                  ))}
                </div>
                {hasMoreUnchanged ? (
                  <p className="border-t border-border-subtle px-3 py-2 text-xs text-text-soft">
                    {t('lists.repairPreviewMoreUnchanged', { count: preview.unchanged.length - unchangedPreview.length })}
                  </p>
                ) : null}
            </section>
          </div>
        </div>

        <div className="flex justify-end gap-2 border-t border-border-subtle p-4">
          <button
            type="button"
            className="rounded-lg border border-border-subtle px-4 py-2 text-sm font-medium text-text-soft transition-colors hover:bg-background-elevated"
            onClick={onCancel}
            disabled={repairing}
          >
            {t('common.cancel')}
          </button>
          <button
            type="button"
            className="rounded-lg bg-danger px-4 py-2 text-sm font-medium text-white transition-colors hover:bg-danger/90 disabled:opacity-60"
            onClick={() => onConfirm([...selectedIds])}
            disabled={repairing || selectedCount === 0}
          >
            {repairing ? t('lists.repairingAutogenerated') : t('lists.repairAutogeneratedApply')}
          </button>
        </div>
      </div>
    </div>
  );

  if (typeof document === 'undefined') return null;
  return createPortal(modal, document.body);
}

